"""OAuth build failures must never become generated configuration."""

import ast
import hashlib
import importlib.util
import io
import os
from pathlib import Path

import pytest
from invoke import Context

TASK_SPEC = importlib.util.spec_from_file_location(
    "oauth2_build_tasks", Path(__file__).resolve().parents[2] / "tasks.py"
)
assert TASK_SPEC and TASK_SPEC.loader
tasks = importlib.util.module_from_spec(TASK_SPEC)
TASK_SPEC.loader.exec_module(tasks)

HELPER_SPEC = importlib.util.spec_from_file_location(
    "oauth2_build_helper",
    Path(__file__).resolve().parents[2] / "scripts/build_oauth2_config.py",
)
assert HELPER_SPEC and HELPER_SPEC.loader
helper = importlib.util.module_from_spec(HELPER_SPEC)
HELPER_SPEC.loader.exec_module(helper)
VALID = b"formatVersion: '1.0.0'\noauth2Config:\n  providers: {}\n"


@pytest.fixture
def destination(tmp_path):
    path = tmp_path / "_oauth2_config.py"
    path.write_bytes(b"previous module\n")
    return path


def _responses(monkeypatch, outputs):
    calls = []
    pending = iter(outputs)

    original_open = Path.open

    def open_input(path, *args, **options):
        if path.parent != helper.INPUT_ROOT:
            return original_open(path, *args, **options)
        calls.append((path, args, options))
        output = next(pending)
        if isinstance(output, Exception):
            raise output
        return io.BytesIO(output)

    monkeypatch.setattr(Path, "open", open_input)
    return calls


def test_valid_pair_preserves_original_bytes_and_module_format(
    destination, monkeypatch
):
    second = VALID.replace(b"\n", b"\r\n") + "# Unicode: café\r\n".encode()
    calls = _responses(monkeypatch, [VALID, second])
    helper.build_oauth2_config(destination)
    pair = {"actions_config": VALID.decode(), "default_user_config": second.decode()}
    expected = (
        "# coding: utf-8\n# Note: autogenerated file.\n"
        "# To regenerate this file use: inv build-oauth2-config.\n\n"
        "# Repository-owned public inputs: action_server/oauth2/*.yaml.\n# No hosted client registrations are provided. Use private custom OAuth settings.\n\n"
        f"FILE_CONTENTS = {repr(pair)}\n"
        f"INPUT_SHA256 = {repr({name: hashlib.sha256(pair[key].encode()).hexdigest() for key, name in helper.INPUTS})}\n"
    )
    assert destination.read_bytes() == expected.encode()
    module = ast.parse(destination.read_bytes())
    assert ast.literal_eval(module.body[0].value) == pair
    assert len(calls) == 2
    for (key, name), (path, args, options) in zip(helper.INPUTS, calls):
        assert path == helper.INPUT_ROOT / name
        assert args == ("rb",)
        assert options == {}
    assert list(destination.parent.iterdir()) == [destination]


@pytest.mark.parametrize("stage", [0, 1])
@pytest.mark.parametrize(
    "failure",
    [
        PermissionError("private diagnostic"),
        OSError("private diagnostic"),
        FileNotFoundError("private input location"),
    ],
)
def test_first_or_second_owned_read_failure_is_preserved(
    destination, monkeypatch, stage, failure
):
    calls = _responses(monkeypatch, [VALID] * stage + [failure])
    with pytest.raises(helper.OAuth2ConfigBuildError) as caught:
        helper.build_oauth2_config(destination)
    assert caught.value.__cause__ is failure
    assert "private" not in str(caught.value)
    assert len(calls) == stage + 1
    assert destination.read_bytes() == b"previous module\n"
    assert list(destination.parent.iterdir()) == [destination]


@pytest.mark.parametrize("stage", [0, 1])
@pytest.mark.parametrize(
    "body",
    [
        b"",
        b" \r\n\t",
        b"\xff",
        b"[broken: private diagnostic",
        b"null",
        b"scalar",
        b"[]",
        b'{"message":"Not Found","status":"404"}',
        b"{}",
        b"oauth2Config: []",
        b"oauth2Config: {}",
        b"oauth2Config:\n  providers: null",
        b"oauth2Config:\n  providers: []",
    ],
)
def test_invalid_payload_never_replaces_module(destination, monkeypatch, stage, body):
    calls = _responses(monkeypatch, [VALID] * stage + [body])
    with pytest.raises(helper.OAuth2ConfigBuildError) as caught:
        helper.build_oauth2_config(destination)
    assert "private diagnostic" not in str(caught.value)
    assert len(calls) == stage + 1
    assert destination.read_bytes() == b"previous module\n"
    assert list(destination.parent.iterdir()) == [destination]


def test_temporary_write_failure_preserves_previous_and_removes_owned_temp(
    destination, monkeypatch
):
    _responses(monkeypatch, [VALID, VALID])
    failure = OSError("private write detail")
    original = helper.tempfile.NamedTemporaryFile

    def temporary_file(**options):
        stream = original(**options)

        def fail_write(contents):
            raise failure

        monkeypatch.setattr(stream, "write", fail_write)
        return stream

    monkeypatch.setattr(helper.tempfile, "NamedTemporaryFile", temporary_file)
    with pytest.raises(
        helper.OAuth2ConfigBuildError, match="replacement failed"
    ) as caught:
        helper.build_oauth2_config(destination)
    assert caught.value.__cause__ is failure
    assert destination.read_bytes() == b"previous module\n"
    assert list(destination.parent.iterdir()) == [destination]


def test_atomic_replace_failure_preserves_previous_and_removes_owned_temp(
    destination, monkeypatch
):
    _responses(monkeypatch, [VALID, VALID])
    failure = OSError("private replacement detail")

    def replace(source, target):
        assert Path(source).parent == destination.parent
        assert target == destination
        raise failure

    monkeypatch.setattr(helper.os, "replace", replace)
    with pytest.raises(
        helper.OAuth2ConfigBuildError, match="replacement failed"
    ) as caught:
        helper.build_oauth2_config(destination)
    assert caught.value.__cause__ is failure
    assert destination.read_bytes() == b"previous module\n"
    assert list(destination.parent.iterdir()) == [destination]


def test_cleanup_failure_cannot_hide_primary_replace_failure(destination, monkeypatch):
    _responses(monkeypatch, [VALID, VALID])
    primary = OSError("private primary")

    def replace(*args):
        raise primary

    unlink = Path.unlink

    def cannot_unlink(path, **options):
        if path.name.startswith(".oauth2-config-"):
            raise OSError("private cleanup detail")
        return unlink(path, **options)

    monkeypatch.setattr(helper.os, "replace", replace)
    monkeypatch.setattr(Path, "unlink", cannot_unlink)
    with pytest.raises(
        helper.OAuth2ConfigBuildError, match="replacement failed"
    ) as caught:
        helper.build_oauth2_config(destination)
    assert caught.value.__cause__ is primary
    assert caught.value.__notes__ == ["Owned OAuth2 temporary cleanup also failed"]
    assert destination.read_bytes() == b"previous module\n"
    for path in destination.parent.glob(".oauth2-config-*"):
        unlink(path)


def test_cli_preserves_safe_error_without_private_cause(capsys, monkeypatch):
    def fail(*args):
        try:
            raise OSError("private acquisition body and path")
        except OSError as cause:
            raise helper.OAuth2ConfigBuildError(
                "OAuth2 acquisition failed (exit 17)"
            ) from cause

    monkeypatch.setattr(helper, "build_oauth2_config", fail)
    assert helper.main() == 1
    captured = capsys.readouterr()
    assert captured.out == ""
    assert captured.err == "OAuth2 acquisition failed (exit 17)\n"


def test_invoke_delegates_to_package_poetry_with_replacement_environment(
    tmp_path, monkeypatch
):
    monkeypatch.setattr(tasks, "CURDIR", tmp_path)
    monkeypatch.setenv("VIRTUAL_ENV", "/foreign/tool/environment")
    for name in (
        "POETRY_ACTIVE",
        "CONDA_PREFIX",
        "CONDA_DEFAULT_ENV",
        "PYTHONHOME",
        "PYTHONPATH",
    ):
        monkeypatch.setenv(name, "foreign-outer-environment")
    monkeypatch.setenv("GH_TOKEN", "fixture-token")
    calls = []

    def package_gateway(context, *args, **options):
        calls.append((Path.cwd(), args, options))

    monkeypatch.setattr(tasks, "run", package_gateway)
    previous = Path.cwd()
    tasks.build_oauth2_config.body(Context())
    assert Path.cwd() == previous
    cwd, command, options = calls[0]
    assert cwd == tmp_path
    assert command == ("poetry", "run", "python", "scripts/build_oauth2_config.py")
    assert options["replace_env"] is True
    assert "VIRTUAL_ENV" not in options["env"]
    for name in (
        "POETRY_ACTIVE",
        "CONDA_PREFIX",
        "CONDA_DEFAULT_ENV",
        "PYTHONHOME",
        "PYTHONPATH",
    ):
        assert name not in options["env"]
        assert os.environ[name] == "foreign-outer-environment"
    assert options["env"]["GH_TOKEN"] == "fixture-token"
    assert os.environ["VIRTUAL_ENV"] == "/foreign/tool/environment"


def test_invoke_read_failure_preserves_previous_module(tmp_path, monkeypatch):
    original_root = tasks.CURDIR
    destination = tmp_path / "src/actions/server/_oauth2_config.py"
    destination.parent.mkdir(parents=True)
    destination.write_bytes(b"previous module\n")
    monkeypatch.setattr(tasks, "CURDIR", tmp_path)

    def package_gateway(*args, **kwargs):
        spec = importlib.util.spec_from_file_location(
            "oauth2_build", original_root / "scripts/build_oauth2_config.py"
        )
        assert spec and spec.loader
        helper = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(helper)
        helper.INPUT_ROOT = tmp_path / "missing-owned-inputs"
        helper.build_oauth2_config(destination)

    monkeypatch.setattr(tasks, "run", package_gateway)
    with pytest.raises(RuntimeError, match="could not be read"):
        tasks.build_oauth2_config.body(Context())
    assert destination.read_bytes() == b"previous module\n"
