"""Build the public community OAuth catalog and operator template offline."""

from __future__ import annotations

import hashlib
import os
import stat
import sys
import tempfile
from pathlib import Path

import yaml

INPUT_ROOT = Path(__file__).resolve().parents[1] / "oauth2"
INPUTS = (
    ("actions_config", "actions-oauth-config.yaml"),
    ("default_user_config", "oauth-config.yaml"),
)
MAX_INPUT_BYTES = 65536


class OAuth2ConfigBuildError(RuntimeError):
    """Build failure whose message contains no input payload."""


class _UniqueKeyLoader(yaml.SafeLoader):
    """Reject ambiguous public inputs rather than silently selecting a key."""


def _mapping(loader, node):
    mapping = {}
    for key_node, value_node in node.value:
        key = loader.construct_object(key_node)
        if not isinstance(key, str) or key in mapping:
            raise yaml.YAMLError("Duplicate or non-string configuration key")
        mapping[key] = loader.construct_object(value_node)
    return mapping


_UniqueKeyLoader.add_constructor(
    yaml.resolver.BaseResolver.DEFAULT_MAPPING_TAG, _mapping
)


def _acquire(file_name: str) -> str:
    path = INPUT_ROOT / file_name
    try:
        if not stat.S_ISREG(path.lstat().st_mode):
            raise OAuth2ConfigBuildError(
                f"OAuth2 input must be a regular file: {file_name}"
            )
        with path.open("rb") as stream:
            raw = stream.read(MAX_INPUT_BYTES + 1)
    except OSError as error:
        raise OAuth2ConfigBuildError(
            f"OAuth2 owned input could not be read: {file_name}"
        ) from error
    if len(raw) > MAX_INPUT_BYTES:
        raise OAuth2ConfigBuildError(f"OAuth2 input is too large: {file_name}")
    try:
        contents = raw.decode("utf-8", errors="strict")
    except UnicodeDecodeError as error:
        raise OAuth2ConfigBuildError(
            f"OAuth2 input is not UTF-8: {file_name}"
        ) from error
    if not contents.strip():
        raise OAuth2ConfigBuildError(f"OAuth2 input is blank: {file_name}")
    try:
        document = yaml.load(contents, Loader=_UniqueKeyLoader)
    except yaml.YAMLError as error:
        raise OAuth2ConfigBuildError(
            f"OAuth2 input is malformed YAML: {file_name}"
        ) from error
    if not isinstance(document, dict):
        raise OAuth2ConfigBuildError(f"OAuth2 input must be a mapping: {file_name}")
    oauth2_config = document.get("oauth2Config")
    if not isinstance(oauth2_config, dict):
        raise OAuth2ConfigBuildError(
            f"OAuth2 input requires an oauth2Config mapping: {file_name}"
        )
    if not isinstance(oauth2_config.get("providers"), dict):
        raise OAuth2ConfigBuildError(
            f"OAuth2 input requires a providers mapping: {file_name}"
        )
    # Neither this catalog nor this template claims a community hosted registration.
    # Credentials belong in the operator's private --oauth2-settings file, never here.
    if document != {"formatVersion": "1.0.0", "oauth2Config": {"providers": {}}}:
        raise OAuth2ConfigBuildError(
            f"OAuth2 public input requires the versioned empty community catalog: {file_name}"
        )
    return contents


def build_oauth2_config(destination: Path) -> None:
    """Validate both inputs before replacing the generated module atomically."""
    contents = {key: _acquire(file_name) for key, file_name in INPUTS}
    input_hashes = {
        file_name: hashlib.sha256(contents[key].encode("utf-8")).hexdigest()
        for key, file_name in INPUTS
    }
    module = f"""# coding: utf-8
# Note: autogenerated file.
# To regenerate this file use: inv build-oauth2-config.

# Repository-owned public inputs: action_server/oauth2/*.yaml.
# No hosted client registrations are provided. Use private custom OAuth settings.

FILE_CONTENTS = {repr(contents)}
INPUT_SHA256 = {repr(input_hashes)}
"""
    temporary_path = None
    primary_error = None
    try:
        with tempfile.NamedTemporaryFile(
            mode="w",
            encoding="utf-8",
            newline="\n",
            dir=destination.parent,
            prefix=".oauth2-config-",
            suffix=".tmp",
            delete=False,
        ) as stream:
            temporary_path = Path(stream.name)
            stream.write(module)
        os.replace(temporary_path, destination)
    except OSError as error:
        primary_error = OAuth2ConfigBuildError("OAuth2 module replacement failed")
        raise primary_error from error
    finally:
        if temporary_path is not None:
            try:
                temporary_path.unlink(missing_ok=True)
            except OSError as error:
                if primary_error is not None:
                    primary_error.add_note("Owned OAuth2 temporary cleanup also failed")
                else:
                    raise OAuth2ConfigBuildError(
                        "Owned OAuth2 temporary cleanup failed"
                    ) from error
    print(f"Writing OAuth2 configs to: {destination}")


def main() -> int:
    destination = (
        Path(__file__).resolve().parents[1] / "src/actions/server/_oauth2_config.py"
    )
    try:
        build_oauth2_config(destination)
    except OAuth2ConfigBuildError as error:
        print(str(error), file=sys.stderr)
        for note in getattr(error, "__notes__", ()):
            print(note, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
